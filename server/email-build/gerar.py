from pathlib import Path
root = Path(__file__).resolve().parents[2]
api = root / 'server/api'
def body(path):
    value = path.read_text(encoding='utf-8')
    return value.replace('<?php\n', '', 1).replace('declare(strict_types=1);\n', '', 1)
renderer = body(api / 'email/confirmacao.php')
renderer = renderer.replace("require_once __DIR__ . '/emailAssets.php';\n", '')
template = (api / 'email/confirmacao.html').read_text(encoding='utf-8')
renderer = renderer.replace("    return strtr(file_get_contents(__DIR__ . '/confirmacao.html'), $replacements);", "    $template = <<<'MORABEZA_EMAIL_HTML'\n" + template + "\nMORABEZA_EMAIL_HTML;\n    return strtr($template, $replacements);")
qr = body(api / 'vendor/qrcode.php').replace('?>', '')
parts = [body(api / 'email/emailAssets.php'), renderer, qr]
for name in ['dadosReserva.php', 'comprovativo.php']:
    parts.append(body(api / 'email' / name).replace("require_once __DIR__ . '/confirmacao.php';\n", ''))
    parts[-1] = parts[-1].replace("require_once __DIR__ . '/../vendor/qrcode.php';\n", '')
endpoint = body(root / 'server/email-build/send_email-endpoint.php')
for name in ['dadosReserva.php', 'comprovativo.php']:
    endpoint = endpoint.replace("    require_once __DIR__ . '/email/" + name + "';\n", '')
result = "<?php\ndeclare(strict_types=1);\n// Complete deployment file, generated by server/email-build/gerar.py.\n// Email template, data helpers and PDF generator are embedded below.\n\n"
result += '\n'.join(parts)
result += '\n' + body(root / 'server/email-build/comprovativo-endpoint.php')
result += "\nfunction executarEmailReserva(): void {\n" + endpoint + "\n}\n\n"
result += "if (isset($_SERVER['SCRIPT_FILENAME']) && realpath($_SERVER['SCRIPT_FILENAME']) === __FILE__) {\n    if (($_GET['action'] ?? '') === 'comprovativo') {\n        executarComprovativoReserva();\n    } else {\n        executarEmailReserva();\n    }\n}\n"
(api / 'send_email.php').write_text(result, encoding='utf-8')
print('Generated complete send_email.php with embedded HTML and PDF helpers.')
